#!/usr/bin/env bash
# Real two-worker check of segmented indexing. Prints a markdown report on stdout.
#   scripts/cluster_segments_check.sh [PORT] > docs/evidence/k/segments.md
# Head + worker w1 (has the footage) + worker w2 (joined with `cw join`, NO footage on it: it streams from the head).
# Runs the same two recordings three ways and compares what ended up in each run's private store:
#   A) 10 s segments across both workers   B) one task per recording   C) like A, with w2 killed part-way.
# All processes run on this machine; nothing here is a speed measurement.
set -u
PORT="${1:-7850}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
CW="${CW:-}"; if [ -z "$CW" ]; then for c in "$REPO"/rust/target-k/release/cw "$REPO"/rust/target/release/cw; do [ -x "$c" ] && CW="$c" && break; done; fi
[ -x "$CW" ] || { echo "set CW=/path/to/cw" >&2; exit 2; }
command -v sqlite3 >/dev/null && command -v python3 >/dev/null || { echo "needs sqlite3 and python3" >&2; exit 2; }
T="$(mktemp -d /tmp/cwseg.XXXXXX)"; PIDS=()
cleanup() { for p in "${PIDS[@]:-}"; do [ -n "$p" ] && kill -9 "$p" 2>/dev/null; done; rm -rf "$T"; }
trap cleanup EXIT INT TERM
H="http://127.0.0.1:$PORT"; api() { curl -s -m 15 "$@"; }
mkroot() { mkdir -p "$1/vision/data"; ln -s "$REPO/vision/models" "$1/vision/models"; ln -s "$REPO/vision/footage" "$1/vision/footage"; cp "$REPO/vision/modules.json" "$REPO/vision/rules.json" "$1/vision/"; }
mkroot "$T/head"; mkroot "$T/w1"; mkdir -p "$T/w2home"
# Deterministic settings so the three runs are comparable frame for frame: every frame, whole picture, no skipping gates.
echo '{"configured":true,"cameras":[],"process":{"mode":"custom","blur_on":false,"blank_on":false,"same_on":false,"every":1,"width":512,"detect_mode":"full","segment_secs":10}}' > "$T/head/vision/watch.json"
CW_ROOT="$T/head" CW_AUTH=off "$CW" head --port "$PORT" --no-local-worker >"$T/head.log" 2>&1 & PIDS+=($!)
for i in $(seq 1 50); do api "$H/api/health" >/dev/null && break; sleep 0.2; done
CW_ROOT="$T/w1" CW_WORKER_ID=w1 CW_NODE_NAME=w1 "$CW" worker --head 127.0.0.1 --port "$PORT" >"$T/w1.log" 2>&1 & PIDS+=($!)
CW_HOME="$T/w2home" CW_WORKER_ID=w2 "$CW" join 127.0.0.1 --port "$PORT" --name w2 >"$T/w2.log" 2>&1 & W2=$!; PIDS+=($W2)
for i in $(seq 1 60); do N=$(api "$H/api/v1/cluster" | python3 -c 'import json,sys; print(len(json.load(sys.stdin)["nodes"]))' 2>/dev/null || echo 0); [ "$N" -ge 2 ] && break; sleep 1; done
[ "${N:-0}" -ge 2 ] || { echo "workers did not register"; tail -5 "$T/w2.log"; exit 1; }
sleep 4
MEDIA='["vision/footage/people-detection.mp4","vision/footage/person-bicycle-car-detection.mp4"]'
run() { # name segment -> id
  local R ID; R=$(api -X POST -H 'Content-Type: application/json' -d "{\"name\":\"$1\",\"media\":$MEDIA,\"segment_secs\":$2}" "$H/api/v1/benchmarks")
  ID=$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("id",""))' "$R"); echo "$ID"
}
wait_done() { for i in $(seq 1 200); do [ "$(api "$H/api/v1/benchmarks" | python3 -c 'import json,sys; print(1 if json.load(sys.stdin).get("running") else 0)')" = 1 ] || return 0; sleep 1; done; }
A=$(run "A segments x2 workers" 10); wait_done
B=$(run "B single task per file" 0); wait_done
C=$(run "C segments, w2 killed" 8) ; sleep 7; kill -9 $W2 2>/dev/null; wait_done
D="$T/head/vision/data/bench"
cat <<MD
# Segmented indexing across two workers

Generated by \`scripts/cluster_segments_check.sh\` on $(date -u +%FT%TZ) ($(uname -sm)). Head, worker w1 and worker w2 all run on **this one machine**.
Worker w2 was started with \`cw join 127.0.0.1\` with an empty data dir: it has **no footage** and read every recording from the head over HTTP
(\`/api/v1/worker/media/{id}/stream\`, ranges, worker token). Settings were fixed so every frame is analysed: every frame, whole picture, no gates.
Recordings: people-detection.mp4 (49.67 s, 12 fps) and person-bicycle-car-detection.mp4 (53.92 s, 12 fps) = 1243 frames.

## Runs
MD
python3 - "$D" "$A" "$B" "$C" <<'PY'
import json,sys
d,ids=sys.argv[1],sys.argv[2:]
print("| run | tasks | wall s | workers (parts / inferred) | decoded | inferred | skipped (overlap) |")
print("|---|---|---|---|---|---|---|")
for i in ids:
    r=json.load(open(f"{d}/{i}.json"))
    w=", ".join("%s %d/%d"%(x["id"].split("|")[-1],x["tasks"],x["inferred"]) for x in r["workers"])
    f=r["frames"]
    print(f"| {r['name']} | {r['tasks']} | {r['wall_s']} | {w} | {f['decoded']} | {f['inferred']} | {f['skipped']} |")
PY
cat <<MD

\`decoded\` is larger in A/C because each part after the first re-reads 2 s before its start to warm the tracker. Those frames are decoded, tracked and **not indexed**: they are the \`skipped\` figure.

## What ended up in each run's store (sqlite, one file per run)
MD
for X in A B C; do eval "ID=\$$X"; echo; echo "### run $X ($ID)"; echo '```'; sqlite3 "$D/$ID.db" "select 'observations', count(*), 'distinct ids', count(distinct observation_id) from observations; select 'detections', count(*), 'distinct ids', count(distinct detection_id) from detections; select 'tracks', count(distinct track_id) from detections; select 'jobs (state, inferred)', group_concat(json_extract(body,'\$.state')||' '||json_extract(body,'\$.coverage.inferred'), '; ') from jobs;"; echo '```'; done
echo; echo "## Comparison with the single-task run (B)"; echo '```'
for X in A C; do eval "ID=\$$X"; sqlite3 "$D/$ID.db" "attach '$D/$B.db' as b; select '$X vs B: observation ids in $X', count(*), ' also in B', sum(observation_id in (select observation_id from b.observations)), ' | B total', (select count(*) from b.observations) from main.observations; select '$X vs B: detection ids in $X', count(*), ' also in B', sum(detection_id in (select detection_id from b.detections)), ' | B total', (select count(*) from b.detections) from main.detections; select '$X vs B: track ids shared', count(distinct track_id) from main.detections where track_id in (select track_id from b.detections);"; done; echo '```'
echo; echo "## Which PC ran which part, run A"; echo '```'
python3 - "$D/$A.json" <<'PY'
import json,sys
r=json.load(open(sys.argv[1]))
for p in r["parts"]:
    print("%-28s start %5.1fs  %s"%(p["key"].split("-")[-2]+"-"+p["key"].split("-")[-1], p["start_s"], "; ".join("%s inferred %d (%s)"%(w["worker"].split("|")[-1],w["inferred"],w["state"]) for w in p["workers"])))
PY
echo '```'
echo; echo "## Run C: w2 killed (kill -9) about 7 s in"; echo '```'
python3 - "$D/$C.json" "$H" <<'PY'
import json,sys,urllib.request
r=json.load(open(sys.argv[1]))
print("state:", r["state"], "| wall", r["wall_s"], "s | parts", r["tasks"])
c=json.load(urllib.request.urlopen(sys.argv[2]+"/api/v1/cluster"))
for n in c["nodes"]: print("node", n["id"].split("|")[-1], n["state"])
print("tasks re-leased (generation > 1):", [(t["task_id"][-8:], t["generation"], t["state"]) for t in c["tasks"] if t["generation"]>1])
for p in r["parts"]:
    if len(p["workers"])>1 or any(w["state"]!="completed" for w in p["workers"]):
        print("part", p["key"][-6:], "ran on", [(w["worker"].split("|")[-1], w["inferred"], w["state"]) for w in p["workers"]])
PY
echo '```'
